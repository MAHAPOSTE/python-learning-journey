# Arithmetic Operators
a = 2
b = 4
c = a + b
print(c)

# Assignment Operators
d = 4 - 2
print(d)

e = 4
e += 2
print(e) # incrementing the value of b by 2

f = 4
f -= 1
print(f) # decrementing the value of b by 1

# Comparison Operators
g = 5 >= 3
print(g) # True

h = 5 != 3
print(h) # True

# Logical Operators
i = True and False
print(i) # False

j = True or False
print(j) # True

k = not True
print(k) # False
